"""Verification Agent: validates specialist findings before final summarization."""

from langchain_core.messages import HumanMessage, SystemMessage

from src.llm import get_llm
from src.logger import get_logger
from src.state import ReviewState
from src.output_cleaner import clean_verified_report

_llm = get_llm()
_log = get_logger("verifier")

_SYSTEM_PROMPT = """You are SentinelCode's Verification Agent.

Your role is to validate code-review findings generated by other AI agents.
You must NOT invent new findings. Only verify, reject, merge, downgrade, or
group findings that appear in the supplied specialist reports.

For every finding, check:
1. Is it supported by direct evidence in the supplied code diff?
2. Is the technical reasoning correct?
3. Is the severity justified?
4. Is the recommended fix technically valid and relevant?
5. Is it duplicated by another finding?

Important rules:
- Keep security findings when direct evidence exists, including SQL injection,
  hardcoded credentials, command injection, XSS, path traversal, insecure
  deserialization, and authentication failures.
- Preserve CWE IDs when they are correct and supported by the code evidence.
- Reject impossible claims. For example, do not report division by zero when
  code divides only by a constant such as 100.
- A finding must identify a concrete code pattern from the diff.
- Reject findings whose own explanation states that the problem does not exist.
- Reject generic category labels that add no new evidence beyond an accepted
  specific finding.
- Merge duplicate findings from multiple agents.

SQL injection rules:
- If SQL injection is accepted for a query, reject generic "missing sanitization"
  or "input validation" findings for the same query as duplicates.
- Do not recommend sanitizing input as the primary SQL injection defense.
  Parameterized queries or prepared statements are the primary fix.
- Do not claim that submitted code is fixed unless the code diff itself contains
  the parameterized-query fix.

Sensitive data rules:
- Reject "sensitive data exposure" unless the diff directly logs, returns,
  stores, or exposes a password, API key, token, secret, or personally
  identifiable information (PII).
- PII means personal information such as a full name, email address, phone
  number, address, government ID, or account credential.

Test-coverage rules:
- Accept a test-related finding only if it is specific and technically valid.
- If the diff contains no tests, test command output, coverage data, or explicit
  testing requirement, do not claim that specific tests are missing.
- Group all unsupported generic test claims into ONE item titled:
  "Unverifiable test-coverage claims".
- Do not list each rejected generic test suggestion separately.

Output limits:
- Maximum 5 accepted findings.
- Maximum 3 needs-human-review findings.
- Maximum 3 rejected findings.
- Keep each finding concise.
- Do not output Markdown tables.
- Do not write long explanations.
- If a section has no items, write "None."

Return exactly this structure:

## Verified Findings

### Accepted
- [SEVERITY | CONFIDENCE] Finding title
  - Evidence: exact code pattern or diff evidence
  - Fix: concise valid remediation
  - Source: agent name(s)

### Needs Human Review
- [SEVERITY | CONFIDENCE] Finding title
  - Reason: why the evidence is incomplete or uncertain
  - Source: agent name(s)

### Rejected Findings
- Finding title
  - Reason: why it is incorrect, unsupported, duplicate, or irrelevant
"""

_REPORT_SECTIONS = [
    ("bug_report", "Logic & Bug Detector"),
    ("security_report", "Security Agent"),
    ("quality_report", "Code Quality Agent"),
    ("test_report", "Test Coverage Agent"),
]


def _build_evidence_packet(state: ReviewState) -> str:
    """Build a compact input containing the code diff and specialist reports."""
    reports = []

    for key, name in _REPORT_SECTIONS:
        findings = state.get(key, [])
        if findings:
            reports.append(f"## {name}\n" + "\n".join(findings))

    report_text = "\n\n".join(reports) if reports else "No specialist findings."

    return (
        f"## Code Diff\n{state['code_diff']}\n\n"
        f"## Specialist Reports\n{report_text}"
    )


def verifier_node(state: ReviewState) -> dict:
    """Validate findings and return a concise evidence-based verification report."""
    _log.info("Verifying specialist findings...")

    evidence_packet = _build_evidence_packet(state)

    response = _llm.invoke([
        SystemMessage(content=_SYSTEM_PROMPT),
        HumanMessage(content=evidence_packet),
    ])

    verified_report = clean_verified_report(response.content)

    return {"verified_report": verified_report}