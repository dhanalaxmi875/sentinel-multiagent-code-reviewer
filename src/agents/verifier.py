"""Verification Agent: validates specialist findings before final summarization."""

from langchain_core.messages import HumanMessage, SystemMessage

from src.llm import get_llm
from src.logger import get_logger
from src.state import ReviewState

_llm = get_llm()
_log = get_logger("verifier")

_SYSTEM_PROMPT = """You are SentinelCode's Verification Agent.

Your role is to validate code-review findings generated by other AI agents.
You must not invent new findings. Only verify, reject, merge, or downgrade
findings that appear in the supplied specialist reports.

For every finding, check:
1. Is it supported by evidence in the supplied code diff?
2. Is the technical reasoning correct?
3. Is the severity justified?
4. Is the recommended fix valid and relevant?
5. Is it a duplicate of another finding?

Important rules:
- Keep SQL injection, hardcoded credentials, command injection, XSS, path traversal,
  insecure deserialization, and authentication failures when evidence exists.
- Reject impossible claims. Example: do not report division by zero when division is
  only by a constant such as 100.
- Keep only specific, technically valid test recommendations supported by the shown code.
- Mark vague or weak findings as LOW confidence instead of treating them as facts.
- Merge duplicate reports from multiple agents.
- Do not write long explanations.
- Do not output Markdown tables.

- A finding must identify a concrete code pattern from the diff.
- Reject findings whose own explanation says the problem does not exist.
- Reject generic category labels that add no new evidence beyond another accepted finding.
- Do not report “missing sanitization” separately if the same evidence is already accepted as SQL injection.
- Do not report sensitive-data exposure unless the code actually logs, returns, stores, or exposes sensitive data.
- Do not claim that code is fixed; this review analyzes the submitted diff, not a hypothetical corrected version.

- Reject a finding if its own reason states that the problem does not exist.
- Reject generic findings that are duplicates of an accepted specific finding.
- Do not retain “missing sanitization” separately when SQL injection has already been accepted from the same query.
- Do not retain “sensitive data exposure” unless the diff directly logs, returns, stores, or exposes a password, token, secret, or personally identifiable information.

Return exactly this structure:

## Verified Findings

### Accepted
- [SEVERITY | CONFIDENCE] Finding title
  - Evidence: exact code pattern or diff evidence
  - Fix: concise valid remediation
  - Source: agent name(s)

### Needs Human Review
- [SEVERITY | CONFIDENCE] Finding title
  - Reason: why the evidence is incomplete or uncertain
  - Source: agent name(s)

### Rejected Findings
- Finding title
  - Reason: why it is incorrect, unsupported, duplicate, or irrelevant

If a section has no items, write "None."
"""

_REPORT_SECTIONS = [
    ("bug_report", "Logic & Bug Detector"),
    ("security_report", "Security Agent"),
    ("quality_report", "Code Quality Agent"),
    ("test_report", "Test Coverage Agent"),
]


def _build_evidence_packet(state: ReviewState) -> str:
    """Build a compact input containing code evidence and specialist reports."""
    reports = []

    for key, name in _REPORT_SECTIONS:
        items = state.get(key, [])
        if items:
            reports.append(f"## {name}\n" + "\n".join(items))

    report_text = "\n\n".join(reports) if reports else "No specialist findings."

    return (
        f"## Code Diff\n{state['code_diff']}\n\n"
        f"## Specialist Reports\n{report_text}"
    )


def verifier_node(state: ReviewState) -> dict:
    """Validate agent findings and return an evidence-based verification report."""
    _log.info("Verifying specialist findings...")

    evidence_packet = _build_evidence_packet(state)

    response = _llm.invoke([
        SystemMessage(content=_SYSTEM_PROMPT),
        HumanMessage(content=evidence_packet),
    ])

    return {"verified_report": response.content}